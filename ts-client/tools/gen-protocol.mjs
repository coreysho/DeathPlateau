// Generate Client-TS's protocol tables from the engine's, which is the only place these numbers
// are authoritative. Re-run it whenever the engine's prot files change rather than hand-editing
// the output: a protocol table maintained by hand is a protocol table that drifts.
//
//   node gen-protocol.mjs <engine-dir> <clientts-src-dir> [--write]
//
// Without --write it reports what would change and touches nothing.
//
// Three engine files feed this. ServerGameProt holds the top-level server packets; ServerGameZoneProt
// holds the ones nested inside UPDATE_ZONE_* (they share the same 0-255 opcode space, so they belong
// in one enum and one size table, which is how Client-TS already has it); ClientGameProt holds what
// the client sends.

import * as fs from 'fs';
import * as path from 'path';

// Same packet, different name on each side. Client-TS's name wins, because its handlers are written
// against it - we are porting numbers, not renaming a codebase.
const ALIASES = {
    LOC_MERGE: 'P_LOCMERGE',            // the engine's own source carries a todo to rename it this
    RESET_CLIENT_VARCACHE: 'VARP_SYNC', // both are opcode-size 0 "reset vars to the server's set"
    REPORT_ABUSE: 'SEND_SNAPSHOT',      // identical payload: g8 offender, g1 reason, gbool mute
};

const [engineDir, ctsSrc, ...rest] = process.argv.slice(2);
const WRITE = rest.includes('--write');
if (!engineDir || !ctsSrc) {
    console.error('usage: node gen-protocol.mjs <engine-dir> <clientts-src-dir> [--write]');
    process.exit(2);
}

const read = p => fs.readFileSync(p, 'utf8');

/** name -> {op, size} from the engine's `static readonly NAME = new XProt(op, size);` */
function engineTable(file, cls) {
    const re = new RegExp(`static readonly (\\w+) = new ${cls}\\((\\d+),\\s*(-?\\d+)\\)`, 'g');
    const out = new Map();
    for (const m of read(file).matchAll(re)) {
        out.set(ALIASES[m[1]] ?? m[1], { op: +m[2], size: +m[3] });
    }
    return out;
}

/**
 * Which packet names Client-TS's code actually uses, and where.
 *
 * This deliberately scans the handler code rather than the enum, for two reasons. A name present in
 * the enum proves nothing - it may be a constant nobody reads. And this generator overwrites the
 * enum, so reading it back would just be reading our own last run.
 */
function referenced(srcDir, prot, enumFile) {
    const found = new Map();
    const re = new RegExp(`\\b${prot}\\.(\\w+)\\b`, 'g');
    const walk = d => {
        for (const e of fs.readdirSync(d, { withFileTypes: true })) {
            const p = path.join(d, e.name);
            if (e.isDirectory()) walk(p);
            else if (e.name.endsWith('.ts') && path.resolve(p) !== path.resolve(enumFile)) {
                // drop string literals first, or the `#/io/ServerProt.js` in every import line
                // reads as a packet called `js`
                const text = read(p).replace(/'[^'\n]*'|"[^"\n]*"/g, "''");
                for (const m of text.matchAll(re)) {
                    if (!found.has(m[1])) found.set(m[1], new Set());
                    found.get(m[1]).add(path.relative(srcDir, p));
                }
            }
        }
    };
    walk(srcDir);
    return found;
}

const pad = (s, n) => String(s).padEnd(n);

// ---------------------------------------------------------------- server -> client

function buildServer(engine, existing) {
    const used = new Set([...engine.values()].map(v => v.op));
    // Names Client-TS knows that our engine never sends. Their handlers are dead code. Rather than
    // leave them on their 274 opcodes - where a future engine packet reusing that number would make
    // a stale handler fire - they get opcodes the engine does not use, so they can never match.
    const orphanOps = new Map();
    let spare = 255;
    for (const n of [...existing].filter(n => !engine.has(n))) {
        while (used.has(spare) && spare > 0) spare--;
        used.add(spare);
        orphanOps.set(n, spare--);
    }

    const L = [];
    L.push('// GENERATED by ts-client/tools/gen-protocol.mjs - do not edit by hand.');
    L.push("// Source of truth: the engine's ServerGameProt.ts and ServerGameZoneProt.ts.");
    L.push('//');
    L.push('// Zone packets (those nested inside UPDATE_ZONE_*) share the top-level opcode space and');
    L.push('// live here too, which is how Client-TS already had them.');
    L.push('export const enum ServerProt {');
    const missing = [];
    for (const [name, { op, size }] of [...engine].sort((a, b) => a[1].op - b[1].op)) {
        const known = existing.has(name);
        if (!known) missing.push({ name, op, size });
        L.push(`    ${pad(name + ' =', 26)} ${String(op).padStart(3)},${known ? '' : '  // TODO: no handler in Client-TS'}`);
    }
    if (orphanOps.size) {
        L.push('');
        L.push('    // Client-TS handles these; our engine has no such packet. Parked on opcodes the');
        L.push('    // engine does not use, so the handlers still compile but can never fire.');
        for (const [n, op] of orphanOps) L.push(`    ${pad(n + ' =', 26)} ${String(op).padStart(3)},`);
    }
    L.push('};');
    L.push('');
    L.push('// Indexed by opcode. 0 = no payload, -1 = one size byte follows, -2 = two.');
    L.push('// prettier-ignore');
    L.push('export const ServerProtSizes = [');
    const sizes = new Array(256).fill(0);
    for (const { op, size } of engine.values()) sizes[op] = size;
    for (let i = 0; i < 256; i += 10) {
        L.push('    ' + sizes.slice(i, i + 10).map(s => String(s).padStart(2)).join(', ') + (i + 10 < 256 ? ',' : ''));
    }
    L.push('];');
    return { text: L.join('\n') + '\n', missing, orphans: [...orphanOps.keys()] };
}

// ---------------------------------------------------------------- client -> server

function buildClient(engine, existing, refs) {
    // Outbound names are not passive. The engine closes the connection on an opcode it does not know
    // (NetworkPlayer.ts: `if (!packetType) { close() }`), so a name Client-TS sends that our engine
    // lacks cannot be parked on a spare opcode the way an inbound one can - that would disconnect the
    // player the first time the client sent it. They are left out of the enum instead, so the build
    // fails at the send sites and someone has to decide what to do about each one.
    const dropped = [...existing].filter(n => !engine.has(n));

    const L = [];
    L.push('// GENERATED by ts-client/tools/gen-protocol.mjs - do not edit by hand.');
    L.push("// Source of truth: the engine's ClientGameProt.ts.");
    if (dropped.length) {
        L.push('//');
        L.push('// Deliberately absent - these are 274-client packets our 377 engine does not know, and');
        L.push('// it closes the connection on an unknown opcode, so they must not be sent at all:');
        for (const n of dropped) {
            const where = [...(refs.get(n) ?? [])];
            L.push(`//   ${pad(n, 24)} ${where.length ? 'sent from ' + where.join(', ') : 'unreferenced'}`);
        }
    }
    L.push('export const enum ClientProt {');
    const missing = [];
    for (const [name, { op, size }] of [...engine].sort((a, b) => a[1].op - b[1].op)) {
        const known = existing.has(name);
        if (!known) missing.push({ name, op, size });
        L.push(`    ${pad(name + ' =', 26)} ${String(op).padStart(3)},${known ? '' : '  // TODO: Client-TS never sends this'}`);
    }
    L.push('};');
    return { text: L.join('\n') + '\n', missing, dropped };
}

// ---------------------------------------------------------------- run

const serverEngine = new Map([
    ...engineTable(path.join(engineDir, 'src/network/game/server/ServerGameProt.ts'), 'ServerGameProt'),
    ...engineTable(path.join(engineDir, 'src/network/game/server/ServerGameZoneProt.ts'), 'ServerGameZoneProt'),
]);
const clientEngine = engineTable(path.join(engineDir, 'src/network/game/client/ClientGameProt.ts'), 'ClientGameProt');

const serverFile = path.join(ctsSrc, 'io/ServerProt.ts');
const clientFile = path.join(ctsSrc, 'io/ClientProt.ts');
const serverRefs = referenced(ctsSrc, 'ServerProt', serverFile);
const clientRefs = referenced(ctsSrc, 'ClientProt', clientFile);
const serverExisting = new Set(serverRefs.keys());
const clientExisting = new Set(clientRefs.keys());

const dup = t => {
    const seen = new Map();
    for (const [n, v] of t) {
        if (seen.has(v.op)) throw new Error(`duplicate opcode ${v.op}: ${n} and ${seen.get(v.op)}`);
        seen.set(v.op, n);
    }
};
dup(serverEngine);
dup(clientEngine);

const srv = buildServer(serverEngine, serverExisting);
const cli = buildClient(clientEngine, clientExisting, clientRefs);

console.log(`ServerProt  ${serverEngine.size} packets (top-level + zone)`);
console.log(`  Client-TS already handles  ${serverEngine.size - srv.missing.length}`);
console.log(`  needs a handler (${String(srv.missing.length).padStart(2)})        ${srv.missing.map(m => m.name).join(' ') || '-'}`);
console.log(`  parked, engine never sends ${srv.orphans.join(' ') || '-'}`);
console.log();
console.log(`ClientProt  ${clientEngine.size} packets`);
console.log(`  Client-TS already sends    ${clientEngine.size - cli.missing.length}`);
console.log(`  never sent (${String(cli.missing.length).padStart(2)})             ${cli.missing.map(m => m.name).join(' ') || '-'}`);
console.log(`  dropped, engine would kick ${cli.dropped.join(' ') || '-'}`);
console.log();

if (WRITE) {
    fs.writeFileSync(serverFile, srv.text);
    fs.writeFileSync(clientFile, cli.text);
    console.log(`written: ${serverFile}`);
    console.log(`written: ${clientFile}`);
} else {
    console.log('(dry run - pass --write to apply)');
}
